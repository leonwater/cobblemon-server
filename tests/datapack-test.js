// 바닐라 1.21.1 서버 + 봇 2명으로 데이터팩 로직 검증 (모드 전용 명령은 run.sh가 비워둠)
const mineflayer = require('mineflayer')
const { Rcon } = require('rcon-client')
const assert = require('assert')
const sleep = ms => new Promise(r => setTimeout(r, ms))

const join = name => new Promise((res, rej) => {
  const b = mineflayer.createBot({ host: 'localhost', port: 25566, username: name, version: '1.21.1', auth: 'offline' })
  b.once('spawn', () => res(b)); b.once('error', rej); b.once('kicked', r => rej(new Error('kicked ' + r)))
})

;(async () => {
  const rc = await Rcon.connect({ host: 'localhost', port: 25576, password: 'test', timeout: 30000 })  // 야생 지형 생성 중엔 서버가 몇 초 느려짐
  const cmd = async c => { const r = await rc.send(c); console.log('>', c, '→', r.slice(0, 300)); return r }
  const ok = async (c, msg) => assert.match(await cmd(c), /passed/, msg)
  const gym = async p => cmd(`scoreboard players get ${p} poke.gym`)
  const pos = async (p, i) => Math.floor(parseFloat((await cmd(`data get entity ${p} Pos[${i}]`)).match(/(-?[\d.]+)d?$/)[1]))
  const dim = async p => (await cmd(`data get entity ${p} Dimension`)).match(/"([^"]+)"$/)[1]
  const at = async (p, d, x, z, msg) => {
    assert.equal(await dim(p), d, msg); assert.equal(await pos(p, 0), x, msg); assert.equal(await pos(p, 2), z, msg)
  }
  const waitFor = async (c, re) => { for (let i = 0; i < 30 && !re.test(await cmd(c)); i++) await sleep(500) }
  const warp = async (p, key) => cmd(`execute as ${p} run function poke:warp/${['farm', 'wild'].includes(key) ? 'go' : 'fixed'} {key:"${key}"}`)

  // 건물이 지어질 때까지 (load 후 60틱)
  await waitFor('data get storage poke:state', /build: 4.*farm: 2|farm: 2.*build: 4/)
  await ok('execute in poke:hub if block 0 64 3 minecraft:polished_deepslate', '튜토리얼 방 바닥')
  await cmd('execute in poke:hub run forceload add 0 200'); await sleep(1500)  // 짓고 나면 풀려 있음
  await ok('execute in poke:hub if block 0 64 200 minecraft:air', '1·8. 예전 허공 마을 삭제')
  await cmd('execute in poke:town run forceload add -30 -80 130 10'); await sleep(2000)
  await ok('execute in poke:town if block 0 -59 5 minecraft:red_carpet', '회의장 붉은 카펫')
  await ok('execute in poke:town if block -14 -58 -9 minecraft:stripped_dark_oak_log', '회의장 기둥')
  await ok('execute in poke:town if block 0 -60 -60 minecraft:polished_andesite', '상점가 길')
  await ok('execute in poke:town if block -16 -54 -63 minecraft:blue_concrete', '5. 프렌들리 숍 파란 지붕')
  await cmd('execute in poke:town run forceload add 130 -50 245 15'); await sleep(2500)
  await ok('execute in poke:town if block 40 -58 -46 minecraft:quartz_pillar', '5. 1번 체육관 건물')
  await ok('execute in poke:town if block 160 -58 12 minecraft:quartz_pillar', '5. 8번 체육관 건물')
  await ok('execute in poke:town if block 200 -58 -46 minecraft:quartz_pillar', '5. 사천왕 본부')
  await ok('execute in poke:town if block -40 0 0 minecraft:barrier', '1. 마을 둘레 벽')
  await cmd('execute in poke:farm run forceload add 64 40 80 60'); await sleep(1500)  // 짓고 나면 농장 청크는 풀려 있음
  await ok('execute in poke:farm if block 73 0 50 minecraft:barrier', '농장 둘레 벽')

  let A = await join('A'), B = await join('B'); await sleep(1500)
  await at('A', 'poke:hub', 0, 3, '튜토리얼 방에서 시작')
  assert.match(await cmd('data get entity A playerGameType'), /: 2$/, '튜토리얼 방은 모험 모드')

  // 4·7. 규칙
  assert.match(await cmd('gamerule keepInventory'), /true/, '인벤세이브')
  await ok('execute as A if predicate poke:has_saturation', '배고픔 없음')
  await cmd('execute in minecraft:overworld run summon minecraft:zombie 0 -59 0')
  await cmd('execute in minecraft:overworld run summon minecraft:villager 2 -59 0 {NoAI:1b}')
  await sleep(1000)
  assert.match(await cmd('execute in minecraft:overworld if entity @e[type=zombie]'), /failed/, '좀비 제거')
  await ok('execute in minecraft:overworld if entity @e[type=villager]', '주민은 유지')

  // 튜토리얼 → 회의장, 보상은 처음 한 번만
  await cmd('execute as A run function poke:tutorial/finish')
  assert.match(await cmd('clear A minecraft:leather_boots 0'), /Found 1 /, '첫 완료: 러닝 슈즈')
  await at('A', 'poke:town', 0, 6, '추가 2. 튜토리얼 후 회의장')
  assert.match(await cmd('data get entity A playerGameType'), /: 2$/, '마을은 모험 모드')
  await cmd('execute as A run function poke:admin/reset_me'); await sleep(500)
  await at('A', 'poke:hub', 0, 3, 'reset_me → 튜토리얼 방')
  await cmd('execute as A run function poke:tutorial/finish')
  assert.match(await cmd('clear A minecraft:leather_boots 0'), /Found 1 /, '두 번째 완료: 보상 없음')
  await cmd('item replace entity A armor.feet from entity A container.0'); await sleep(500)
  assert.match(await cmd('attribute A minecraft:generic.movement_speed get'), /0\.13/, '러닝 슈즈 +30%')

  // 예전 마을(허공)에 남아 있던 플레이어 → 회의장으로 옮김
  await cmd('execute in poke:hub run tp A 0.5 65 200.5'); await sleep(500)
  await at('A', 'poke:town', 0, 6, '허공 공간의 기존 플레이어 → 회의장')
  // 8. 워프: 회의장·상점가·체육관은 고정, 농장·야생은 마지막 위치
  await warp('A', 'street'); await sleep(300)
  await at('A', 'poke:town', 0, -28, '상점가')
  await warp('A', 'gym'); await sleep(300)
  await at('A', 'poke:town', 25, -17, '체육관 거리 입구')
  await warp('A', 'farm'); await sleep(500)
  await at('A', 'poke:farm', 0, -3, '농장 처음: 입구')
  assert.match(await cmd('data get entity A playerGameType'), /: 0$/, '농장은 서바이벌')
  await cmd('execute in poke:farm run tp A 20.5 -59 50.5'); await sleep(2500)
  await cmd('execute as A run trigger home'); await sleep(500)
  await at('A', 'poke:town', 0, 6, '/trigger home → 회의장')
  await warp('A', 'farm'); await sleep(500)
  await at('A', 'poke:farm', 20, 50, '농장: 마지막 위치로')
  await cmd('execute in poke:farm run tp A 0.5 -59 -6.5'); await sleep(500)
  await at('A', 'poke:town', 0, 6, '농장 "회의장으로" 발판')
  await warp('A', 'farm'); await sleep(500)
  await at('A', 'poke:farm', 20, 50, '발판으로 나와도 마지막 위치 유지')

  // 4·추가 1. 야생 첫 스폰: 모두 같은 자리, 꽃 숲(포켓몬 평균 레벨 최저) 칸
  await warp('A', 'wild'); await waitFor('data get entity A Dimension', /poke:wild/)
  const wx = await pos('A', 0), wz = await pos('A', 2)
  await ok(`execute in poke:wild if biome ${wx} 70 ${wz} minecraft:flower_forest`, '스폰 지점 바이옴 = 꽃 숲')
  await cmd('execute as B run function poke:tutorial/finish')
  await warp('B', 'wild'); await waitFor('data get entity B Dimension', /poke:wild/)
  assert.equal(await pos('B', 0), wx, 'B도 같은 야생 스폰'); assert.equal(await pos('B', 2), wz)
  await cmd(`execute in poke:wild run tp A ${wx + 10} ~ ${wz}`); await sleep(2500)
  const lx = await pos('A', 0)
  await cmd('execute as A run trigger home'); await sleep(500)
  await warp('A', 'wild'); await waitFor('data get entity A Dimension', /poke:wild/)
  assert.equal(await pos('A', 0), lx, '야생 두 번째부터는 마지막 위치')

  // ── 리그: 배지 체육관 8 + 사천왕 (승패는 모드가 gym/win·gym/lose 를 호출 → 여기선 직접 호출) ──
  await cmd('execute as A run trigger home'); await cmd('execute as B run trigger home'); await sleep(500)
  const g = async p => cmd(`scoreboard players get ${p} poke.gym`)
  await cmd('execute as B run function poke:gym/try/2')
  assert.doesNotMatch(await g('B'), /has /, '5. 배지1 없으면 2번 체육관 입장 불가')
  await at('B', 'poke:town', 50, -17, '거절되면 2번 체육관 앞으로')
  await cmd('execute as A run function poke:gym/try/1')
  assert.match(await g('A'), /has 1 /, '1번 체육관 입장')
  await at('A', 'poke:town', 50, -28, '경기장(관장 앞)으로')
  await cmd('execute as B run function poke:gym/try/1')
  assert.doesNotMatch(await g('B'), /has /, '3. 관장 한 명에 도전자 한 명')
  await cmd('execute as A run function poke:gym/win'); await sleep(300)
  assert.match(await cmd('tag A list'), /poke\.badge1/, '승리 → 배지 1')
  assert.match(await cmd('clear A minecraft:gold_nugget[minecraft:custom_data={pokeserver:"badge1"}] 0'), /Found 1 /, '배지 아이템 지급')
  assert.doesNotMatch(await g('A'), /has /, '승리 후 잠금 해제')
  await at('A', 'poke:town', 50, -18, '승리 후 체육관 앞으로')
  await cmd('execute as A run function poke:gym/try/1')
  assert.doesNotMatch(await g('A'), /has /, '7. 이긴 체육관은 다시 도전 불가')
  await cmd('execute as B run function poke:gym/try/1')
  assert.match(await g('B'), /has 1 /, 'A가 끝나면 B 입장')
  await cmd('execute as B run function poke:gym/lose'); await sleep(300)
  assert.doesNotMatch(await g('B'), /has /, '패배 → 밖으로, 잠금 해제')
  assert.doesNotMatch(await cmd('tag B list'), /badge1/, '패배는 배지 없음')
  // 입장 발판 (틱에서 감지)
  await cmd('execute in poke:town run tp B 50.5 -59 -20.5'); await sleep(500)
  assert.match(await g('B'), /has 1 /, '입장 발판 → 1번 체육관')
  await cmd('execute in poke:town run tp B 50.5 -59 -22.5'); await sleep(500)
  assert.doesNotMatch(await g('B'), /has /, '나가기 발판 → 밖으로')
  // 로그아웃하면 잠금 해제
  await cmd('execute as A run function poke:gym/try/2')
  assert.match(await g('A'), /has 2 /, '배지1 → 2번 체육관 입장')
  A.quit(); await sleep(1500)
  await cmd('tag B add poke.badge1'); await cmd('execute as B run function poke:gym/try/2')
  assert.match(await g('B'), /has 2 /, 'A 로그아웃 → 2번 체육관 잠금 해제')
  await cmd('execute as B run function poke:gym/leave')
  A = await join('A'); await sleep(1500)
  assert.doesNotMatch(await g('A'), /has /, 'A 재접속 시 체육관 상태 초기화')

  // 사천왕: 배지 8개 필요, 네 명 연속 승리, 지면 처음부터, 클리어 후 재도전 불가
  await cmd('execute as A run function poke:gym/try/9')
  assert.doesNotMatch(await g('A'), /has /, '배지 8개 없으면 사천왕 불가')
  for (let n = 1; n <= 8; n++) await cmd(`tag A add poke.badge${n}`)
  await cmd('execute as A run function poke:gym/try/9')
  await at('A', 'poke:town', 206, -40, '사천왕 1번 방')
  await cmd('execute as A run function poke:gym/win'); await sleep(200)
  await at('A', 'poke:town', 206, -29, '이기면 2번 방')
  await cmd('execute as A run function poke:gym/win'); await sleep(200)
  await cmd('execute as A run function poke:gym/lose'); await sleep(300)
  await at('A', 'poke:town', 195, -17, '3번째에서 지면 밖으로')
  await cmd('execute as A run function poke:gym/try/9')
  await at('A', 'poke:town', 206, -40, '다시 도전하면 1번 방부터')
  for (let k = 0; k < 4; k++) { await cmd('execute as A run function poke:gym/win'); await sleep(200) }
  assert.match(await cmd('tag A list'), /poke\.e4clear/, '네 명 연속 승리 → 사천왕 클리어')
  await at('A', 'poke:town', 206, 4, '명예의 전당')
  await cmd('execute in poke:town run tp A 202.5 -59 4.5'); await sleep(500)
  await at('A', 'poke:town', 195, -17, '명예의 전당 나가기 발판')
  await cmd('execute as A run function poke:gym/try/9')
  assert.doesNotMatch(await g('A'), /has /, '7. 사천왕도 클리어 후 재도전 불가')
  await cmd('kill B'); await sleep(1500)
  assert.doesNotMatch(await g('B'), /has /, '사망 시 잠금 해제')

  console.log('ALL PASS'); A.quit(); B.quit(); await rc.end(); process.exit(0)
})().catch(e => { console.error('FAIL', e.message); process.exit(1) })
